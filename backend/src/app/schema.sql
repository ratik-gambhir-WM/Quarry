);

CREATE TABLE templates (
 catalog_sequence BIGINT GENERATED ALWAYS AS IDENTITY UNIQUE,
                 template_id TEXT COLLATE "C" PRIMARY KEY,
                 template_json TEXT COLLATE "C" NOT NULL CHECK ((template_json IS JSON))
             , owner_user_id BIGINT REFERENCES users(id) ON DELETE RESTRICT);

CREATE TABLE template_assets (
                 asset_id TEXT COLLATE "C" PRIMARY KEY,
                 template_id TEXT COLLATE "C" NOT NULL,
                 content_type TEXT COLLATE "C" NOT NULL CHECK (content_type LIKE 'image/%'),
                 asset_data BYTEA NOT NULL CHECK (length(asset_data) > 0),
                 FOREIGN KEY (template_id) REFERENCES templates(template_id) ON DELETE CASCADE
             );

CREATE TABLE template_metadata (
                 template_id TEXT COLLATE "C" PRIMARY KEY,
                 kind TEXT COLLATE "C" NOT NULL CHECK (kind IN ('diagram', 'commentary')),
                 description TEXT COLLATE "C" NOT NULL,
                 source TEXT COLLATE "C" NOT NULL CHECK (source IN ('builtin', 'import')),
                 checksum TEXT COLLATE "C",
                 created_at TEXT COLLATE "C" NOT NULL,
                 FOREIGN KEY (template_id) REFERENCES templates(template_id) ON DELETE CASCADE
             );

CREATE TABLE template_previews (
                 template_id TEXT COLLATE "C" PRIMARY KEY,
                 content_type TEXT COLLATE "C" NOT NULL CHECK (content_type = 'image/png'),
                 preview_data BYTEA NOT NULL CHECK (length(preview_data) > 0),
                 width BIGINT NOT NULL CHECK (width > 0),
                 height BIGINT NOT NULL CHECK (height > 0),
                 FOREIGN KEY (template_id) REFERENCES templates(template_id) ON DELETE CASCADE
             );

CREATE TABLE apps (
                 app_id TEXT COLLATE "C" PRIMARY KEY, display_name TEXT COLLATE "C" NOT NULL,
                 metadata_json TEXT COLLATE "C" NOT NULL CHECK((metadata_json IS JSON)),
                 created_at TEXT COLLATE "C" NOT NULL, last_seen_at TEXT COLLATE "C" NOT NULL
