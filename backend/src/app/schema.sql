-- Fresh PostgreSQL schema, equivalent to the final SQLite marker 18.
-- Serialized JSON and timestamps stay text to preserve fingerprints and API values.
CREATE TABLE app_metadata (
                key TEXT COLLATE "C" PRIMARY KEY NOT NULL,
                value TEXT COLLATE "C" NOT NULL
            );

CREATE TABLE users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 1 AND 9007199254740991),
                first_name TEXT COLLATE "C" NOT NULL,
                last_name TEXT COLLATE "C" NOT NULL,
                email TEXT COLLATE "C" NOT NULL UNIQUE,
                username TEXT COLLATE "C" NOT NULL UNIQUE,
                password_hash TEXT COLLATE "C" NOT NULL,
                job_title TEXT COLLATE "C",
                created_at TEXT COLLATE "C" NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
                updated_at TEXT COLLATE "C" NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
            );

CREATE TABLE auth_sessions (
                token_hash TEXT COLLATE "C" PRIMARY KEY NOT NULL,
                user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                created_at BIGINT NOT NULL,
                expires_at BIGINT NOT NULL CHECK(expires_at > created_at),
                revoked_at BIGINT
            );

CREATE TABLE reminders (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 1 AND 9007199254740991),
                reminder TEXT COLLATE "C" NOT NULL,
                notes TEXT COLLATE "C" NOT NULL,
                date TEXT COLLATE "C" NOT NULL,
                link TEXT COLLATE "C" NOT NULL,
                time TEXT COLLATE "C",
                deal TEXT COLLATE "C",
                tag TEXT COLLATE "C",
                created_at TEXT COLLATE "C" NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
                updated_at TEXT COLLATE "C" NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
            );

CREATE TABLE deals (
                deal_id TEXT COLLATE "C" PRIMARY KEY NOT NULL CHECK (length(trim(deal_id)) > 0),
                user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
                deal_name TEXT COLLATE "C" NOT NULL CHECK (length(trim(deal_name)) > 0),
                deal_code TEXT COLLATE "C" CHECK (deal_code IS NULL OR length(trim(deal_code)) > 0),
                engagement_type TEXT COLLATE "C" NOT NULL CHECK (engagement_type IN ('buy_side', 'sell_side', 'other')),
                transaction_type TEXT COLLATE "C" NOT NULL CHECK (transaction_type IN ('platform_acquisition', 'add_on_acquisition', 'strategic_acquisition', 'carve_out', 'merger', 'divestiture', 'recapitalization', 'growth_equity', 'other', 'unknown')),
                status TEXT COLLATE "C" NOT NULL CHECK (status IN ('pipeline', 'prepare', 'review_plan_discovery', 'interviews_site_visit', 'debrief_flash_report', 'follow_ups_analysis', 'qa_readout_closeout', 'closed', 'pencils_down')),
                start_date TEXT COLLATE "C" CHECK (start_date IS NULL OR length(trim(start_date)) > 0),
                expected_close_date TEXT COLLATE "C" CHECK (expected_close_date IS NULL OR length(trim(expected_close_date)) > 0),
                actual_close_date TEXT COLLATE "C" CHECK (actual_close_date IS NULL OR length(trim(actual_close_date)) > 0),
                engagement_completed_date TEXT COLLATE "C" CHECK (engagement_completed_date IS NULL OR length(trim(engagement_completed_date)) > 0),
                archived_at TEXT COLLATE "C" CHECK (archived_at IS NULL OR length(trim(archived_at)) > 0),
                created_at TEXT COLLATE "C" NOT NULL,
                updated_at TEXT COLLATE "C" NOT NULL
            );

CREATE TABLE companies (
                company_id TEXT COLLATE "C" PRIMARY KEY NOT NULL,
                user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
                name TEXT COLLATE "C" NOT NULL CHECK (length(trim(name)) > 0),
                website TEXT COLLATE "C" CHECK (website IS NULL OR length(trim(website)) > 0),
                industry TEXT COLLATE "C" CHECK (industry IS NULL OR length(trim(industry)) > 0),
                description TEXT COLLATE "C" CHECK (description IS NULL OR length(trim(description)) > 0),
                created_at TEXT COLLATE "C" NOT NULL,
                updated_at TEXT COLLATE "C" NOT NULL
            );

CREATE TABLE deal_parties (
                deal_party_id TEXT COLLATE "C" PRIMARY KEY NOT NULL,
                deal_id TEXT COLLATE "C" NOT NULL REFERENCES deals(deal_id) ON DELETE CASCADE,
                company_id TEXT COLLATE "C" NOT NULL REFERENCES companies(company_id) ON DELETE RESTRICT,
                role TEXT COLLATE "C" NOT NULL CHECK (role IN ('target', 'buyer', 'seller', 'pe_sponsor', 'portfolio_company', 'parent_company', 'client', 'other')),
                notes TEXT COLLATE "C" CHECK (notes IS NULL OR length(trim(notes)) > 0),
                UNIQUE (deal_id, company_id, role)
            );

CREATE TABLE deal_scopes (
                deal_id TEXT COLLATE "C" NOT NULL REFERENCES deals(deal_id) ON DELETE CASCADE,
                scope TEXT COLLATE "C" NOT NULL CHECK (scope IN ('product_architecture', 'corporate_it', 'cybersecurity', 'application_security', 'sdlc', 'it_organization', 'it_financials')),
                PRIMARY KEY (deal_id, scope)
            );

CREATE TABLE deal_metadata (
                deal_id TEXT COLLATE "C" PRIMARY KEY NOT NULL REFERENCES deals(deal_id) ON DELETE CASCADE,
                key_questions_json TEXT COLLATE "C" NOT NULL DEFAULT '[]'
                    CHECK ((key_questions_json IS JSON) AND json_typeof(key_questions_json::json) = 'array'),
                local_path TEXT COLLATE "C" CHECK (local_path IS NULL OR length(trim(local_path)) > 0),
                sharepoint_link TEXT COLLATE "C" CHECK (sharepoint_link IS NULL OR length(trim(sharepoint_link)) > 0),
                sow_link TEXT COLLATE "C" CHECK (sow_link IS NULL OR length(trim(sow_link)) > 0),
                fact_sheet_link TEXT COLLATE "C" CHECK (fact_sheet_link IS NULL OR length(trim(fact_sheet_link)) > 0),
                rl_link TEXT COLLATE "C" CHECK (rl_link IS NULL OR length(trim(rl_link)) > 0),
                CHECK (NOT (local_path IS NOT NULL AND sharepoint_link IS NOT NULL))
            );

CREATE TABLE assistant_threads (
                thread_id TEXT COLLATE "C" PRIMARY KEY NOT NULL,
                deal_id TEXT COLLATE "C" REFERENCES deals(deal_id) ON DELETE RESTRICT,
                user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                title TEXT COLLATE "C" NOT NULL,
                status TEXT COLLATE "C" NOT NULL DEFAULT 'regular'
                    CHECK (status IN ('regular', 'archived')),
                metadata_json TEXT COLLATE "C" NOT NULL DEFAULT '{}' CHECK ((metadata_json IS JSON)),
                created_at TEXT COLLATE "C" NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
                updated_at TEXT COLLATE "C" NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
                last_message_at TEXT COLLATE "C" NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
                CHECK (length(trim(thread_id)) > 0),
                CHECK (length(trim(title)) > 0)
            );

CREATE TABLE assistant_messages (
                message_id TEXT COLLATE "C" PRIMARY KEY NOT NULL,
                thread_id TEXT COLLATE "C" NOT NULL REFERENCES assistant_threads(thread_id) ON DELETE CASCADE,
                parent_message_id TEXT COLLATE "C" REFERENCES assistant_messages(message_id),
                sequence BIGINT NOT NULL CHECK (sequence >= 0),
                role TEXT COLLATE "C" NOT NULL CHECK (role IN ('user', 'assistant')),
                content TEXT COLLATE "C" NOT NULL,
                status TEXT COLLATE "C" NOT NULL
                    CHECK (status IN ('streaming', 'completed', 'failed', 'cancelled')),
                model TEXT COLLATE "C",
                request_id TEXT COLLATE "C",
                error_code TEXT COLLATE "C",
                metadata_json TEXT COLLATE "C" NOT NULL DEFAULT '{}' CHECK ((metadata_json IS JSON)),
                created_at TEXT COLLATE "C" NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')),
                completed_at TEXT COLLATE "C",
                UNIQUE (thread_id, sequence),
                UNIQUE (thread_id, request_id),
                CHECK (length(trim(message_id)) > 0),
                CHECK (request_id IS NULL OR length(trim(request_id)) > 0)
            );

CREATE TABLE "quarry_files" (
    file_id TEXT COLLATE "C" PRIMARY KEY NOT NULL,
    deal_id TEXT COLLATE "C" NOT NULL REFERENCES deals(deal_id) ON DELETE CASCADE,
    display_name TEXT COLLATE "C" NOT NULL,
    source_uri TEXT COLLATE "C",
    metadata_json TEXT COLLATE "C" NOT NULL DEFAULT '{}' CHECK((metadata_json IS JSON)),
    created_at TEXT COLLATE "C" NOT NULL,
    updated_at TEXT COLLATE "C" NOT NULL,
    deleted_at TEXT COLLATE "C",
    CHECK(length(trim(file_id)) > 0), CHECK(length(trim(deal_id)) > 0),
    CHECK(length(trim(display_name)) > 0), CHECK(source_uri IS NULL OR length(trim(source_uri)) > 0)
);

CREATE TABLE quarry_file_versions (
                version_id        TEXT COLLATE "C" PRIMARY KEY NOT NULL,
                file_id           TEXT COLLATE "C" NOT NULL REFERENCES quarry_files(file_id) ON DELETE CASCADE,
                version_number    BIGINT NOT NULL CHECK (version_number > 0),
                original_filename TEXT COLLATE "C" NOT NULL,
                mime_type         TEXT COLLATE "C" NOT NULL,
                content_sha256    TEXT COLLATE "C" NOT NULL,
                byte_size         BIGINT NOT NULL CHECK (byte_size >= 0),
                is_current        BIGINT NOT NULL DEFAULT 0 CHECK (is_current IN (0, 1)),
                created_at        TEXT COLLATE "C" NOT NULL, uploaded_by_user_id BIGINT REFERENCES users(id) ON DELETE RESTRICT,
                UNIQUE (file_id, version_number),
                UNIQUE (file_id, content_sha256),
                CHECK (length(trim(version_id)) > 0),
                CHECK (length(trim(original_filename)) > 0),
                CHECK (length(content_sha256) = 64)
            );

CREATE TABLE quarry_file_blobs (
                version_id  TEXT COLLATE "C" PRIMARY KEY NOT NULL
                    REFERENCES quarry_file_versions(version_id) ON DELETE CASCADE,
                file_bytes  BYTEA NOT NULL
            );

CREATE TABLE deal_memberships (
    deal_id TEXT COLLATE "C" NOT NULL REFERENCES deals(deal_id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    role TEXT COLLATE "C" NOT NULL CHECK(role IN ('owner','manager','contributor','viewer')),
    added_by_user_id BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    joined_at TEXT COLLATE "C" NOT NULL,
    updated_at TEXT COLLATE "C" NOT NULL,
    revision BIGINT NOT NULL DEFAULT 1 CHECK(revision BETWEEN 1 AND 9007199254740991),
    PRIMARY KEY(deal_id, user_id)
);

CREATE TABLE deal_access_revisions (
    deal_id TEXT COLLATE "C" PRIMARY KEY NOT NULL REFERENCES deals(deal_id) ON DELETE CASCADE,
    revision BIGINT NOT NULL DEFAULT 1 CHECK(revision BETWEEN 1 AND 9007199254740991)
);

CREATE TABLE deal_teams (
    team_id TEXT COLLATE "C" PRIMARY KEY NOT NULL,
    deal_id TEXT COLLATE "C" NOT NULL REFERENCES deals(deal_id) ON DELETE CASCADE,
    name TEXT COLLATE "C" NOT NULL CHECK(length(name) BETWEEN 1 AND 100),
    normalized_name TEXT COLLATE "C" NOT NULL CHECK(length(normalized_name) BETWEEN 1 AND 300),
    created_by_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at TEXT COLLATE "C" NOT NULL,
    updated_at TEXT COLLATE "C" NOT NULL,
    revision BIGINT NOT NULL DEFAULT 1 CHECK(revision BETWEEN 1 AND 9007199254740991),
    UNIQUE(deal_id, normalized_name),
    UNIQUE(deal_id, team_id)
);

CREATE TABLE deal_team_memberships (
    deal_id TEXT COLLATE "C" NOT NULL,
    team_id TEXT COLLATE "C" NOT NULL,
    user_id BIGINT NOT NULL,
    PRIMARY KEY(deal_id, team_id, user_id),
    FOREIGN KEY(deal_id, team_id) REFERENCES deal_teams(deal_id, team_id) ON DELETE CASCADE,
    FOREIGN KEY(deal_id, user_id) REFERENCES deal_memberships(deal_id, user_id) ON DELETE CASCADE
);

CREATE TABLE deal_activity_events (
    event_id TEXT COLLATE "C" PRIMARY KEY NOT NULL,
    deal_id TEXT COLLATE "C" NOT NULL REFERENCES deals(deal_id) ON DELETE CASCADE,
    actor_user_id BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    kind TEXT COLLATE "C" NOT NULL CHECK(kind IN ('membership_backfilled','project_created','member_added','member_role_changed','member_removed','ownership_transferred','team_created','team_renamed','team_deleted','team_member_added','team_member_removed','deal_archived','deal_updated','metadata_updated','document_uploaded')),
    target_id TEXT COLLATE "C",
    created_at TEXT COLLATE "C" NOT NULL
);

CREATE TABLE quarry_current_content (
    deal_id TEXT COLLATE "C" NOT NULL REFERENCES deals(deal_id) ON DELETE CASCADE,
    content_sha256 TEXT COLLATE "C" NOT NULL,
    file_id TEXT COLLATE "C" NOT NULL REFERENCES quarry_files(file_id) ON DELETE CASCADE,
    version_id TEXT COLLATE "C" NOT NULL REFERENCES quarry_file_versions(version_id) ON DELETE CASCADE,
    PRIMARY KEY(deal_id,content_sha256),
    UNIQUE(file_id)
);

CREATE TABLE document_identity_manifests (
    version_id TEXT COLLATE "C" PRIMARY KEY NOT NULL REFERENCES quarry_file_versions(version_id) ON DELETE CASCADE,
    derivation_version BIGINT NOT NULL CHECK(derivation_version IN (1,2)),
    document_id TEXT COLLATE "C" NOT NULL,
    active_generation TEXT COLLATE "C" NOT NULL CHECK(length(active_generation) > 0),
    chunk_count BIGINT NOT NULL CHECK(chunk_count >= 0),
    graph_migrated BIGINT NOT NULL DEFAULT 0 CHECK(graph_migrated IN (0,1))
);

CREATE TABLE document_chunk_identities (
    chunk_id TEXT COLLATE "C" PRIMARY KEY NOT NULL,
    version_id TEXT COLLATE "C" NOT NULL REFERENCES document_identity_manifests(version_id) ON DELETE CASCADE,
    index_generation TEXT COLLATE "C" NOT NULL,
    chunk_index BIGINT NOT NULL CHECK(chunk_index >= 0),
    chunk_sha256 TEXT COLLATE "C" NOT NULL,
    UNIQUE(version_id,index_generation,chunk_index)
);

CREATE TABLE document_image_recovery (
    version_id TEXT COLLATE "C" PRIMARY KEY NOT NULL REFERENCES document_identity_manifests(version_id) ON DELETE CASCADE,
    assembly_json TEXT COLLATE "C" NOT NULL CHECK((assembly_json IS JSON) AND json_typeof(assembly_json::json) = 'object')
);

CREATE TABLE notebooks (
    notebook_id TEXT COLLATE "C" PRIMARY KEY NOT NULL CHECK (length(trim(notebook_id)) > 0),
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    deal_id TEXT COLLATE "C" REFERENCES deals(deal_id) ON DELETE RESTRICT,
    title TEXT COLLATE "C" NOT NULL CHECK (length(trim(title)) BETWEEN 1 AND 300),
    created_at TEXT COLLATE "C" NOT NULL,
    updated_at TEXT COLLATE "C" NOT NULL
);

CREATE TABLE notebook_folders (
    folder_id TEXT COLLATE "C" PRIMARY KEY NOT NULL CHECK (length(trim(folder_id)) > 0),
    notebook_id TEXT COLLATE "C" NOT NULL REFERENCES notebooks(notebook_id) ON DELETE CASCADE,
    name TEXT COLLATE "C" NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 200),
    created_at TEXT COLLATE "C" NOT NULL,
    updated_at TEXT COLLATE "C" NOT NULL,
    UNIQUE (notebook_id, folder_id)
);

CREATE TABLE notebook_notes (
    note_id TEXT COLLATE "C" PRIMARY KEY NOT NULL CHECK (length(trim(note_id)) > 0),
    notebook_id TEXT COLLATE "C" NOT NULL REFERENCES notebooks(notebook_id) ON DELETE CASCADE,
    folder_id TEXT COLLATE "C",
    title TEXT COLLATE "C" NOT NULL DEFAULT '' CHECK (length(title) <= 300),
    blocks_json TEXT COLLATE "C" NOT NULL DEFAULT '[]'
        CHECK ((blocks_json IS JSON) AND json_typeof(blocks_json::json) = 'array'),
    content_schema_version BIGINT NOT NULL DEFAULT 1
        CHECK (content_schema_version = 1),
    revision BIGINT NOT NULL DEFAULT 1
        CHECK (revision BETWEEN 1 AND 9007199254740991),
    created_at TEXT COLLATE "C" NOT NULL,
    updated_at TEXT COLLATE "C" NOT NULL,
    FOREIGN KEY (notebook_id, folder_id)
        REFERENCES notebook_folders(notebook_id, folder_id)
        ON DELETE NO ACTION DEFERRABLE INITIALLY DEFERRED
);

